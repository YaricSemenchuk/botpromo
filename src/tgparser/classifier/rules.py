# Кого ищут: исполнитель или подрядная контора. Отдельным фрагментом, потому
# что «посоветуйте» осмысленно только с ним ("посоветуйте подрядчика"), а
# «нужен/ищу» — ещё и с названием работы (см. _NEED_OBJECT).
_PERFORMER = (
    r"(?:кто|кого|подрядчик\w*|специалист\w*|спец\w*|исполнител\w*|фрилансер\w*"
    r"|агентств\w*|команд\w*|сервис\w*|студи\w*|человек\w*|эксперт\w*|контакт\w*"
    r"|помощ\w*|консультаци\w*)"
)

# То, что просят сделать. Пересекается с тематическим словарём намеренно:
# «нужна раскрутка» — это уже заявка, отдельного маркера намерения там не будет.
_NEED_OBJECT = (
    r"(?:" + _PERFORMER + r"|асо|aso|раскрутк\w*|продвижени\w*|аудит\w*|оптимизаци\w*"
    r"|семантик\w*|локализаци\w*|установк\w*|инсталл\w*|мотив\w*|накрутк\w*|отзыв\w*"
    r"|рейтинг\w*|позици\w*|ключ\w*|метаданн\w*|скриншот\w*|иконк\w*)"
)

# «нужен ASO?» и «нужна раскрутка?» — это не заявка, а зачин рекламы услуг:
# продавец сам задаёт вопрос и сам на него отвечает. Вопросительный знак сразу
# после объекта такую формулировку отсекает.
_NOT_AD_HOOK = r"(?!\s*\?)"

# Маркеры намерения: кто-то ИЩЕТ исполнителя/поставщика. "Сильные" — однозначно
# сигнализируют вопрос/поиск (не встречаются в обычной рекламе услуг).
STRONG_INTENT_MARKERS = [
    r"\bкто\b.{0,25}\b(делает|дела[ею]т)\b",
    r"\bкто\b.{0,25}\b(может|могут)\b.{0,15}\bсдела\w*\b",
    r"\bплатно\b",
    r"где\s+(можно\s+)?(купить|закупить)",
    r"(посовету\w*|подскаж\w*).{0,15}\bкто\b",
    r"у\s+кого\s+можно",
    r"у\s+кого\s+(есть\s+)?свой\s+сервис",
    r"\bкто\b\s+(предоставляет|обеспечивает)",
    r"ком\w*\s+интересно.{0,15}пиш\w*",
    # Прямая заявка: «ищу/нужен/требуется» + кого или что именно. Мимо проходят
    # продавец, ищущий заказчиков, и вопрос о необходимости («нужно ЛИ»).
    #
    # Разрыв — не больше двух слов, и только через пробел/дефис. Иначе в улов
    # попадают реплики внутри тредов, где нужное слово оказалось рядом
    # случайно: «нужен(у кого, что есть в базах)», «нужно начинать особенно
    # нч ключи». Заявка формулируется коротко: «нужна раскрутка», «ищу
    # ASO-специалиста», «нужен дизайнер для АСО».
    r"\b(ищу|ищем|нужен|нужна|нужны|нужно|требуется|требуются)\b"
    r"(?!\s+ли\b)(?!\s+(?:заказчик|клиент)\w*)(?:[ \-]+\w+){0,2}[ \-]+" + _NEED_OBJECT + _NOT_AD_HOOK,
    # Дизайнер — только когда он нужен под стор. «Дизайнер для АСО» (скриншоты,
    # иконка) — наша работа; «дизайнер UI/UX для приложения» — чужая, это
    # продуктовый дизайн, и в улов такое попадать не должно.
    r"\b(нужен|нужна|ищу|ищем|требуется)\b(?:[ \-]+\w+){0,2}[ \-]+дизайнер\w*"
    r"[^.!?]{0,40}\b(асо|aso|скриншот\w*|иконк\w*|стор\w*)",
    # «Посоветуйте/порекомендуйте подрядчика» — без «кто» рядом (оно уже выше).
    r"(посовету\w*|подскаж\w*|порекоменду\w*)\b(?:\W+\w+){0,3}\W+" + _PERFORMER,
    # «Кто может помочь / кто возьмётся». «Кто может подсказать/объяснить» —
    # это вопрос за информацией к соседям по чату, исполнителя там не ищут.
    r"\bкто\b\W+(?:\w+\W+){0,3}(может|поможет|помочь|берет?с[яь]|возьмет?с[яь])"
    r"(?!\W+(?:подсказать|сказать|объяснить|рассказать|посмотреть|поделиться))",
    r"\bесть\s+(?:тут\s+|здесь\s+)?кто\b",
    r"\bкому\s+(скинуть|отправить|написать|скидывать)\b",
    # Прямая покупка
    r"\b(куплю|закуплю|закажу|оплачу)\b",
    r"\b(хочу|хотим|готов\w*)\s+(купить|заказать|оплатить|заплатить|платить)",
    r"сколько\s+стоит\b|\bпочем\b|цена\s+вопроса",
    r"где\s+(?:сейчас\s+)?(закупа\w*|покупа\w*|берет[еа]\b|брать\b|заказыва\w*)",
    # EN
    r"who\s+can\s+do",
    r"looking\s+for",
    r"where\s+to\s+(buy|purchase)",
    r"\bpaid\b",
    r"\bneed\s+(help|someone|a\s+specialist|an?\s+\w+\s+specialist)",
    r"\bany\s+recommendations\b",
    r"\bwho\s+(can|does|is\s+doing)\b",
]

# "Слабые" маркеры — просьба написать в лс. Сама по себе продавцы используют
# её как call-to-action не реже покупателей, поэтому она НЕ должна одна
# перевешивать SELLER_NEGATIVE_MARKERS (см. engine.classify) — но всё ещё
# считается намерением для обычного thematic+intent совпадения.
DM_CONTACT_MARKERS = [
    r"(отпиш\w*|напиш\w*)\w*\s*(в\s*)?(лс|личк\w*)",
    r"\bdm\s+me\b",
]

# DIY: владелец прилы делает ASO сам и спрашивает "как правильно" — тёплый лид.
DIY_META_MARKERS = [
    r"как\s+(лучше|правильно)\s+(указывать|писать|делать|расставлять|прописывать)",
]

